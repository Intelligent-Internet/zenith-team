// Package daemon is the local agent runtime: it discovers the claude/codex CLIs, registers runtimes per company,
// heartbeats over WS with an HTTP fallback, claims runs WS-first, prepares
// execution environments with boardly's workspace design plus the execenv
// provider pass, and streams run transcripts back to the server.
package daemon

import (
	"encoding/json"
	"time"

	"boardly.dev/boardly/server/internal/contentbundle"

	"github.com/google/uuid"

	"boardly.dev/boardly/server/pkg/agent"
	"boardly.dev/boardly/server/pkg/protocol"
)

// AgentEntry describes a single available agent CLI.
type AgentEntry struct {
	// Path is the absolute path the CLI was found at, symlinks kept (see
	// findProviderExecutable), so an upgrade behind it reaches the next run.
	Path string
	// Command is the bare command name or BOARDLY_*_PATH value Path was
	// resolved from, kept so the daemon can re-resolve if the pinned
	// executable later vanishes.
	Command string
	// Model is the daemon-wide model override from BOARDLY_*_MODEL (optional).
	Model string
}

// Runtime is a registered daemon runtime as returned by the server.
type Runtime struct {
	SignIn    *protocol.RuntimeSignIn `json:"signIn,omitempty"`
	ID        string                  `json:"id"`
	CompanyID string                  `json:"companyId"`
	Name      string                  `json:"name"`
	Provider  string                  `json:"provider"`
	Status    string                  `json:"status"`
}

// Run is the daemon-plane run object (the server's DaemonRun): exactly what
// the daemon reads to execute — the routing ids, the enqueue-time context
// document, the resume pointer, and (on a claim only) the run's brt_ auth
// token. Lifecycle fields the daemon never reads — status, attempts,
// timestamps, failure text — are not served and not decoded.
//
// ID is a UUID string generated by PostgreSQL. There is no trigger
// message id beside it any more: the words the run answers arrive frozen in
// Context.Prompt (ADR 0003), so the daemon never resolves a prompt by id.
type Run struct {
	ID                uuid.UUID       `json:"id"`
	CompanyID         string          `json:"companyId"`
	AgentID           string          `json:"agentId"`
	TaskID            string          `json:"taskId,omitempty"`
	ConversationID    string          `json:"conversationId"`
	RuntimeID         string          `json:"runtimeId"`
	Context           json.RawMessage `json:"context,omitempty"`
	ForceFreshSession bool            `json:"forceFreshSession"`
	// AuthToken is the run-scoped brt_ credential minted at claim. The daemon
	// injects it into the agent process as BOARDLY_RUN_TOKEN; it never falls
	// back to its own session token there.
	AuthToken      string `json:"authToken,omitempty"`
	PriorSessionID string `json:"priorSessionId,omitempty"`
	// PriorSessionThroughSeq is the Conversation watermark the prior provider
	// session had received when its Run ended; snapshot items above it were
	// never delivered to that session. Zero when the claim carried none.
	PriorSessionThroughSeq int64 `json:"priorSessionThroughSeq,omitempty"`
}

// RunContext is the run.Context document the enqueue side may attach to a
// run. Every field is optional; absent fields fall back to daemon defaults.
type RunContext struct {
	ChannelInvocation *RunChannelInvocation `json:"channelInvocation,omitempty"`
	Prompt            string                `json:"prompt,omitempty"`
	Agent             RunAgentContext       `json:"agent,omitempty"`
	Company           *RunCompanyContext    `json:"company,omitempty"`
	// ExecutionProfile is the enqueue-time product contract. It is immutable
	// across retries and is the structural source for Schedule isolation and
	// Task prompt/capability policy.
	ExecutionProfile RunExecutionProfileContext `json:"executionProfile,omitempty"`
	// ConnectorSnapshot is the immutable, server-reviewed connector scope.
	// Provider-local paths, commands, credentials, and MCP configuration never
	// enter this document; the daemon re-resolves those immediately before use.
	ConnectorSnapshot *RunConnectorSnapshot `json:"connectorSnapshot,omitempty"`
	// Resources carries company resources relevant to this run; a
	// local_directory entry pinned to this daemon makes the run execute in
	// place under the path lock.
	Resources []RunResourceContext `json:"resources,omitempty"`
	// CompanyReferences are the founder-supplied documents the Company keeps.
	// They are Company-owned rather than tied to one message, so they are
	// placed in the Company workspace and outlive the Run that first saw them.
	ProjectDocuments              []RunAttachedFile `json:"projectDocuments,omitempty"`
	ProjectDocumentRoot           string            `json:"-"`
	ProjectDocumentNames          map[string]string `json:"-"`
	ProjectDocumentTexts          []string          `json:"-"`
	UnavailableProjectDocuments   []string          `json:"-"`
	CompanyReferences             []RunAttachedFile `json:"companyReferences,omitempty"`
	ChannelArtifactIDs            []string          `json:"channelArtifactIds,omitempty"`
	ChannelAttachments            []RunAttachedFile `json:"channelAttachments,omitempty"`
	ChannelAttachmentRoot         string            `json:"-"`
	UnavailableChannelAttachments []string          `json:"-"`
	// ChatWhiteboards are the Whiteboards of the chat the Run answers that its
	// Authorizer can open, newest first: those shared into the channel that
	// tagged the Agent, or those made in the Agent or Task chat.
	ChatWhiteboards []RunWhiteboardContext `json:"chatWhiteboards,omitempty"`
	// TaskAttachments are the files members attached to the Task, on its
	// Conversation's messages. Every Run of the Task receives them under its
	// env root at task-files/<attachment id>/<name>, never in the workspace or
	// the Task's branch: the Runs of one workspace generation (ADR 0014) share
	// a managed Task's root, a handoff's new root downloads them afresh, and an
	// execute-in-place Run's is its own scratch.
	TaskAttachments            []RunAttachedFile `json:"taskAttachments,omitempty"`
	TaskAttachmentRoot         string            `json:"-"`
	UnavailableTaskAttachments []string          `json:"-"`
	// ConversationSnapshot is the frozen pre-trigger chat history, kept raw
	// so the exact server bytes reach context/conversation.json and the
	// rendered history decodes from those same bytes.
	ConversationSnapshot json.RawMessage `json:"conversationSnapshot,omitempty"`
	// Trigger names the member whose message this Run answers. Absent for
	// assignment Runs and for continuations the server composed itself.
	Trigger *RunTriggerContext `json:"trigger,omitempty"`
}

// RunWhiteboardContext names a Whiteboard Artifact by ID and title.
type RunWhiteboardContext struct {
	ID    string `json:"id"`
	Title string `json:"title"`
}

// RunChannelInvocation identifies the shared destination and context revision;
// the execution conversation still owns the private provider session.
type RunChannelInvocation struct {
	ID              string `json:"id"`
	ChannelID       string `json:"channelId"`
	ThreadRootID    string `json:"threadRootId"`
	ContextRevision int64  `json:"contextRevision"`
}

// RunTriggerContext mirrors the trigger attribution the enqueue kernel
// freezes beside the prompt: who wrote the words this Run answers, and when.
type RunTriggerContext struct {
	Author    RunConversationAuthor `json:"author"`
	CreatedAt time.Time             `json:"createdAt"`
}

// RunConversationAuthor is one message's author as the snapshot names it.
type RunConversationAuthor struct {
	ID   string             `json:"id"`
	Kind protocol.ActorKind `json:"kind"`
	Name string             `json:"name"`
}

// RunConversationSnapshot mirrors the bounded chat history the enqueue
// kernel freezes into runs.context. Items ascend by seq, hold chat only and
// never include the trigger; ThroughSeq is the whole stream's watermark
// before it. Separate from the execution package on purpose: the daemon
// does not import the server, and the shared golden proves the two agree.
type RunConversationSnapshot struct {
	SchemaVersion  int                   `json:"schemaVersion"`
	Kind           string                `json:"kind"`
	ConversationID string                `json:"conversationId"`
	ThroughSeq     int64                 `json:"throughSeq"`
	Truncated      bool                  `json:"truncated"`
	Items          []RunConversationItem `json:"items"`
}

// RunConversationItem is one chat message inside a snapshot.
type RunConversationItem struct {
	ID        string                `json:"id"`
	Seq       int64                 `json:"seq"`
	RunID     string                `json:"runId"`
	Author    RunConversationAuthor `json:"author"`
	CreatedAt time.Time             `json:"createdAt"`
	Content   string                `json:"content"`
}

// RunCompanyContext is founder-supplied business context frozen by the
// enqueue kernel. It informs the work but grants no execution authority.
type RunCompanyContext struct {
	BusinessContextPath string   `json:"-"`
	Name                string   `json:"name,omitempty"`
	BusinessContext     string   `json:"businessContext,omitempty"`
	WebsiteURL          string   `json:"websiteUrl,omitempty"`
	AttestedMilestones  []string `json:"attestedMilestones,omitempty"`
}

// RunAttachedFile names one founder-supplied document the Company keeps. The
// daemon places it in the Company workspace before the provider starts, so the
// Agent can read what it was given.
type RunAttachedFile struct {
	ID          string `json:"id"`
	Filename    string `json:"filename"`
	ContentType string `json:"contentType,omitempty"`
	SizeBytes   int64  `json:"sizeBytes,omitempty"`
}

// RunConnectorSnapshot is the complete connector scope frozen for one run.
// A present empty snapshot means no connector is available to that run.
// DiscoveryFresh reports whether the Runtime's discovery was inside the
// freshness window at the claim, so an empty scope can say whether nothing is
// connected or nothing could be verified; nil means an older server did not
// say.
type RunConnectorSnapshot struct {
	SchemaVersion  int                   `json:"schemaVersion"`
	Connectors     []RunConnectorContext `json:"connectors"`
	DiscoveryFresh *bool                 `json:"discoveryFresh,omitempty"`
}

// RunConnectorContext binds a database policy revision to the provider's
// current public tool namespace without copying provider configuration. Name
// is the app's display name, presentation only.
type RunConnectorContext struct {
	ID             string                `json:"id"`
	PolicyRevision int64                 `json:"policyRevision"`
	Source         string                `json:"source"`
	NativeID       string                `json:"nativeId"`
	Name           string                `json:"name,omitempty"`
	ContractDigest string                `json:"contractDigest"`
	Tools          []agent.ConnectorTool `json:"tools"`
}

// RunAgentContext mirrors the agent brief the enqueue kernel freezes into the
// run context (name, instructions, model, thinkingLevel), plus the skill and
// MCP payloads the claim can deliver. customEnv/customArgs were removed:
// nothing server-side ever produced them, so their layering code was
// unreachable by construction.
type RunAgentContext struct {
	Capabilities    RunCapabilitySettings `json:"capabilities,omitempty"`
	DisabledPlugins []RunDisabledPlugin   `json:"disabledPlugins,omitempty"`
	Name            string                `json:"name,omitempty"`
	Title           string                `json:"title,omitempty"`
	Instructions    string                `json:"instructions,omitempty"`
	Model           string                `json:"model,omitempty"`
	ThinkingLevel   string                `json:"thinkingLevel,omitempty"`
	// IsRoot marks the CEO Agent, the root of the reporting tree, frozen at
	// enqueue. Planning authority and the Company main workspace follow it.
	IsRoot       bool            `json:"isRoot,omitempty"`
	McpConfig    json.RawMessage `json:"mcpConfig,omitempty"`
	SkillSetHash string          `json:"skillSetHash,omitempty"`
	SkillRefs    []SkillRefData  `json:"skillRefs,omitempty"`
	Skills       []SkillData     `json:"skills,omitempty"`
}

