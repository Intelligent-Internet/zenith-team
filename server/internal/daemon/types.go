// RunUsageEntry is per-model token usage reported for one run.
type RunUsageEntry struct {
	Provider         string `json:"provider"`
	Model            string `json:"model"`
	InputTokens      int64  `json:"inputTokens"`
	OutputTokens     int64  `json:"outputTokens"`
	CacheReadTokens  int64  `json:"cacheReadTokens"`
	CacheWriteTokens int64  `json:"cacheWriteTokens"`
	// UsageBasis names what the counters measure: this run's own consumption
	// (per_run) or the provider's cumulative totals for the whole resumed
	// session (session_cumulative — the codex basis).
	UsageBasis         string          `json:"usageBasis"`
	CostUSDTicks       *int64          `json:"costUsdTicks,omitempty"`
	ReasoningTokens    *int64          `json:"reasoningTokens,omitempty"`
	Turns              *int32          `json:"turns,omitempty"`
	ProviderDurationMs *int64          `json:"providerDurationMs,omitempty"`
	BillingMode        string          `json:"billingMode"`
	RawJSON            json.RawMessage `json:"rawJson"`
}

// RunDisposition is the daemon's terminal decision for a run: which server
// callback the result funnels into. A closed set — the old open-set Status
// string let "blocked" ride along as an undeclared pseudo-state.
type RunDisposition string

const (
	// RunDispositionCompleted reports the run through the complete callback.
	RunDispositionCompleted RunDisposition = "completed"
	// RunDispositionFailed reports the run through the fail callback with the
	// disposition's FailureReason (empty defers to the server classifier).
	RunDispositionFailed RunDisposition = "failed"
	// RunDispositionCancelled also reports through the fail callback, with
	// the fixed "cancelled" reason when the result carries none.
	RunDispositionCancelled RunDisposition = "cancelled"
)

// RunResult is the outcome of executing a run.
type RunResult struct {
	Disposition RunDisposition `json:"disposition"`
	Comment     string         `json:"comment"`
	SessionID   string         `json:"sessionId,omitempty"`
	// Transcript is the last PostgreSQL-acknowledged durable prefix. Terminal
	// transitions compare it with the Run row before changing state.
	Transcript RunTranscriptProof `json:"transcript"`
	// TaskRoot is the managed worktree root a Task Run executed in, empty for
	// every other Run. handleRun supersedes it when it learns of a handoff
	// only after the Run finished.
	TaskRoot string `json:"-"`
	// FailureReason is forwarded to FailRun on the failed path; empty falls
	// back to the server-side classifier.
	FailureReason string `json:"-"`
	// SessionRolloutMissing: the daemon withheld this run's Codex session
	// because its rollout never reached the store.
	SessionRolloutMissing bool `json:"-"`
	// RetiredSessionID names a session this run was told to resume and then
	// abandoned as unresumable.
	RetiredSessionID string `json:"-"`
	// PendingItem is the one completed item whose durable receipt never came
	// back — the append was sent, the answer may well be committed, and the
	// local head could not advance. Terminal reconciliation replays it to
	// learn what the server actually holds (bug R1); nil is the ordinary case.
	PendingItem *protocol.RunTranscriptAppendRequest `json:"-"`
	Usage       []RunUsageEntry                      `json:"usage,omitempty"`
}

// RunTranscriptProof binds a terminal provider result to the exact durable
// transcript prefix the daemon observed committed. ThroughSeq is the whole of
// that prefix: the server allocates seq under the conversation row lock and
// never rewrites a committed item, so one seq names one history.
type RunTranscriptProof struct {
	ThroughSeq   int64  `json:"throughSeq"`
	FinalItemKey string `json:"finalItemKey,omitempty"`
}
