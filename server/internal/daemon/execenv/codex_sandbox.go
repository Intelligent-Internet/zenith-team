// Background
//
// On macOS, Codex's Seatbelt sandbox in `workspace-write` mode silently
// ignores `[sandbox_workspace_write] network_access = true` (upstream
// openai/codex#10390): DNS is blocked at the syscall layer, so processes
// inside the sandbox cannot reach the Boardly API. Until a fixed Codex
// release ships, the per-run config on macOS falls back to
// `sandbox_mode = "danger-full-access"`.
//
// Linux runs danger-full-access as a deliberate product decision: the containment boundary is whatever the daemon itself runs
// inside (VM, container, dedicated user), because workspace-write restricts
// only writes while reads and network were already unrestricted.
//
// CodexDarwinNetworkAccessFixedVersion is the earliest Codex CLI version in
// which `network_access = true` is honored under Seatbelt on macOS. Empty
// means "no known fixed release yet".
const CodexDarwinNetworkAccessFixedVersion = ""

// codexSandboxPolicy describes how the per-run Codex config.toml should
// configure the sandbox.
type codexSandboxPolicy struct {
	// Mode is the value written as `sandbox_mode = "..."`.
	Mode string
	// NetworkAccess controls `[sandbox_workspace_write] network_access`.
	// Only meaningful when Mode is "workspace-write".
	NetworkAccess bool
	// Reason is a short human-readable label used in warn-level logs.
	Reason string
	// Hint is an optional remediation surfaced when Mode is
	// danger-full-access.
	Hint string
	// OuterSandbox marks danger-full-access chosen because the daemon's
	// macOS sandbox already holds the Run, which is not "unsandboxed".
	OuterSandbox bool
}

// resolveGOOS returns goos, or runtime.GOOS when goos is empty.
func resolveGOOS(goos string) string {
	if goos == "" {
		return runtime.GOOS
	}
	return goos
}

// codexSandboxPolicyFor picks the sandbox policy for the given platform and
// detected Codex CLI version.
func codexSandboxPolicyFor(goos, detectedVersion string) codexSandboxPolicy {
	goos = resolveGOOS(goos)
	if goos != "darwin" {
		return codexSandboxPolicy{
			Mode:   "danger-full-access",
			Reason: "codex on " + goos + ": runs run with the daemon user's real HOME and full filesystem access; isolation comes from the boundary the daemon runs inside",
			Hint:   "run the daemon inside a VM, container, or dedicated Unix user — runs can read and write everything that user can",
		}
	}
	if codexDarwinNetworkAccessFixed(detectedVersion) {
		return codexSandboxPolicy{
			Mode:          "workspace-write",
			NetworkAccess: true,
			Reason:        "codex version includes macOS network_access fix",
		}
	}
	reason := "codex on macOS: seatbelt ignores sandbox_workspace_write.network_access (openai/codex#10390)"
	if detectedVersion == "" {
		reason += " — version unknown, assuming broken"
	}
	return codexSandboxPolicy{
		Mode:   "danger-full-access",
		Reason: reason,
		Hint:   "upgrade Codex CLI (e.g. `brew upgrade codex` or `npm i -g @openai/codex`) once a release including openai/codex#10390 is available to restore workspace-write + network_access",
	}
}

// codexDarwinNetworkAccessFixed returns true if the given detected version is
// known to honor `network_access = true` under Seatbelt on macOS.
func codexDarwinNetworkAccessFixed(detectedVersion string) bool {
	if CodexDarwinNetworkAccessFixedVersion == "" || detectedVersion == "" {
		return false
	}
	atLeast, err := agent.VersionAtLeast(detectedVersion, CodexDarwinNetworkAccessFixedVersion)
	return err == nil && atLeast
}

// boardlyManagedBeginMarker / boardlyManagedEndMarker delimit the block the
// daemon writes into the per-run config.toml. Everything between the markers
// is owned by the daemon and rewritten idempotently; anything outside the
// markers is preserved as-is.
const (
	boardlyManagedBeginMarker = "# BEGIN boardly-managed (do not edit; regenerated by daemon)"
	boardlyManagedEndMarker   = "# END boardly-managed"
)

// renderBoardlyManagedBlock produces the managed block for the given policy.
// The block contains only top-level dotted-key assignments — no `[table]`
// headers — and is hoisted to the top of the file so it neither leaks into
// nor inherits from any surrounding table scope.
func renderBoardlyManagedBlock(policy codexSandboxPolicy) string {
	var b strings.Builder
	b.WriteString(boardlyManagedBeginMarker)
	b.WriteString("\n")
	fmt.Fprintf(&b, "sandbox_mode = %q\n", policy.Mode)
	if policy.Mode == "workspace-write" {
		fmt.Fprintf(&b, "sandbox_workspace_write.network_access = %t\n", policy.NetworkAccess)
	}
	b.WriteString(boardlyManagedEndMarker)
	b.WriteString("\n")
	return b.String()
}

// managedBlockRe captures the daemon-owned block (including markers and any
// trailing blank lines) so it can be replaced idempotently. `\n*` rather than
// `\n?` so reruns don't accumulate blank lines when the block coexists with
// another managed block in the file.
var managedBlockRe = regexp.MustCompile(
	`(?ms)^` + regexp.QuoteMeta(boardlyManagedBeginMarker) +
		`.*?^` + regexp.QuoteMeta(boardlyManagedEndMarker) + `\n*`)

// upsertBoardlyManagedBlock returns the config content with the
// boardly-managed block placed at the very top of the file. Any previously
// written managed block is removed; user content outside markers survives.
func upsertBoardlyManagedBlock(content string, policy codexSandboxPolicy) string {
	content = managedBlockRe.ReplaceAllString(content, "")
	block := renderBoardlyManagedBlock(policy)
	content = strings.TrimLeft(content, "\n")
	if content == "" {
		return block
	}
	return block + "\n" + content
}

// stripLegacySandboxDirectives removes top-level `sandbox_mode = ...` lines
// and any `[sandbox_workspace_write]` section that would conflict with the
// managed block. Only top-level entries are stripped.
func stripLegacySandboxDirectives(content string) string {
	lines := strings.Split(content, "\n")
	out := make([]string, 0, len(lines))
	inLegacyWorkspaceWrite := false
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "[") {
			inLegacyWorkspaceWrite = trimmed == "[sandbox_workspace_write]"
			if inLegacyWorkspaceWrite {
				continue
			}
			out = append(out, line)
			continue
		}
		if inLegacyWorkspaceWrite {
			continue
		}
		if strings.HasPrefix(trimmed, "sandbox_mode") {
			continue
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

// ensureCodexSandboxConfig writes the boardly-managed sandbox block into the
// given config.toml according to the policy. Idempotent: running it twice
// produces the same file contents. The file is created if it doesn't exist.
// Every danger-full-access resolution is logged at warn level so unsandboxed
// runs are visible in daemon logs.
func ensureCodexSandboxConfig(
	configPath string,
	policy codexSandboxPolicy,
	detectedVersion string,
	logger *slog.Logger,
) error {
	data, err := os.ReadFile(configPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read config.toml: %w", err)
	}
	existing := string(data)

	if existing != "" && !managedBlockRe.MatchString(existing) {
		existing = stripLegacySandboxDirectives(existing)
	}

	updated := upsertBoardlyManagedBlock(existing, policy)
	if updated == string(data) {
		return nil
	}

	if policy.Mode == "danger-full-access" && !policy.OuterSandbox && logger != nil {
		version := detectedVersion
		if version == "" {
			version = "unknown"
		}
		attrs := []any{
			"reason", policy.Reason,
			"codex_version", version,
			"config_path", configPath,
		}
		if policy.Hint != "" {
			attrs = append(attrs, "hint", policy.Hint)
		}
		logger.Warn("codex sandbox: running unsandboxed with danger-full-access", attrs...)
	}

	if err := os.WriteFile(configPath, []byte(updated), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}

