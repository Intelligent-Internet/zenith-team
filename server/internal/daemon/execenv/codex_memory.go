package execenv

import (
	"fmt"
	"log/slog"
	"os"
	"regexp"
	"strings"
)

// Codex CLI ships a native auto-memory subsystem: it writes turn summaries to
// `$CODEX_HOME/memories/` and reads them back into model context on the next
// turn. That is an opaque second store outside boardly's explicit context
// model, and it can leak across runs and companies (a reused run home keeps
// memories/, and the CLI may also read the user-level ~/.codex/memories/).
// The daemon therefore disables both the `features.memories` flag and the
// `memories.*` generation/consumption switches in the per-run config.toml.
// The user's global ~/.codex/config.toml is never modified.
//
// The escape hatch is operator-only by design: BOARDLY_-prefixed keys are
// blocked from agent custom env, so only the daemon process environment can
// carry BOARDLY_CODEX_MEMORY.
//
// TOML rejects redefining an existing table — including implicitly via a
// dotted key — so two independent managed blocks adapt to the user's config:
// memory-feature (features.memories) and memory-config (memories.*), each
// injected inside its top-level table when one exists and written at the file
// root in dotted-key form otherwise.

// BoardlyCodexMemoryEnv keeps Codex native memory enabled inside
// daemon-managed runs when set truthy (1, true, yes, on; case-insensitive).
const BoardlyCodexMemoryEnv = "BOARDLY_CODEX_MEMORY"

const (
	boardlyMemoryFeatureBeginMarker = "# BEGIN boardly-managed memory-feature (do not edit; regenerated by daemon)"
	boardlyMemoryFeatureEndMarker   = "# END boardly-managed memory-feature"
	boardlyMemoryConfigBeginMarker  = "# BEGIN boardly-managed memory-config (do not edit; regenerated by daemon)"
	boardlyMemoryConfigEndMarker    = "# END boardly-managed memory-config"
)

// `\n*` rather than `\n?` so reruns don't accumulate blank lines when these
// blocks coexist with the sandbox / multi-agent blocks.
var memoryFeatureBlockRe = regexp.MustCompile(
	`(?ms)^` + regexp.QuoteMeta(boardlyMemoryFeatureBeginMarker) +
		`.*?^` + regexp.QuoteMeta(boardlyMemoryFeatureEndMarker) + `\n*`)

var memoryConfigBlockRe = regexp.MustCompile(
	`(?ms)^` + regexp.QuoteMeta(boardlyMemoryConfigBeginMarker) +
		`.*?^` + regexp.QuoteMeta(boardlyMemoryConfigEndMarker) + `\n*`)

var (
	rootMemoriesTableHeaderRe    = regexp.MustCompile(`^\s*\[\s*memories\s*\]\s*(?:#.*)?$`)
	featuresTableMemoriesRe      = regexp.MustCompile(`^\s*memories\s*=`)
	rootDottedFeaturesMemoriesRe = regexp.MustCompile(`^\s*features\s*\.\s*memories\s*=`)
	memoriesTableGenerateRe      = regexp.MustCompile(`^\s*generate_memories\s*=`)
	memoriesTableUseRe           = regexp.MustCompile(`^\s*use_memories\s*=`)
	rootDottedMemoriesGenerateRe = regexp.MustCompile(`^\s*memories\s*\.\s*generate_memories\s*=`)
	rootDottedMemoriesUseRe      = regexp.MustCompile(`^\s*memories\s*\.\s*use_memories\s*=`)
)

func codexMemoryEnabled() bool {
	return envTruthy(os.Getenv(BoardlyCodexMemoryEnv))
}

// renderBoardlyMemoryFeatureBlock returns the memory-feature block:
// `memories = false` inside a `[features]` table, dotted-key otherwise.
func renderBoardlyMemoryFeatureBlock(inFeaturesTable bool) string {
	var b strings.Builder
	b.WriteString(boardlyMemoryFeatureBeginMarker)
	b.WriteString("\n")
	if inFeaturesTable {
		b.WriteString("memories = false\n")
	} else {
		b.WriteString("features.memories = false\n")
	}
	b.WriteString(boardlyMemoryFeatureEndMarker)
	b.WriteString("\n")
	return b.String()
}

// renderBoardlyMemoryConfigBlock returns the memory-config block: bare keys
// inside a `[memories]` table, dotted-key otherwise.
func renderBoardlyMemoryConfigBlock(inMemoriesTable bool) string {
	var b strings.Builder
	b.WriteString(boardlyMemoryConfigBeginMarker)
	b.WriteString("\n")
	if inMemoriesTable {
		b.WriteString("generate_memories = false\n")
		b.WriteString("use_memories = false\n")
	} else {
		b.WriteString("memories.generate_memories = false\n")
		b.WriteString("memories.use_memories = false\n")
	}
	b.WriteString(boardlyMemoryConfigEndMarker)
	b.WriteString("\n")
	return b.String()
}

// stripUserMemoryDirectives removes user-written directives that would
// conflict with the managed blocks, in every encoding. Other tables
// (`[features.experimental]`, `[memories.advanced]`, ...) are preserved.
func stripUserMemoryDirectives(content string) string {
	lines := strings.Split(content, "\n")
	out := make([]string, 0, len(lines))
	currentTable := ""
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if rootFeaturesTableHeaderRe.MatchString(line) {
			currentTable = "[features]"
			out = append(out, line)
			continue
		}
		if rootMemoriesTableHeaderRe.MatchString(line) {
			currentTable = "[memories]"
			out = append(out, line)
			continue
		}
		if strings.HasPrefix(trimmed, "[") {
			currentTable = trimmed
			out = append(out, line)
			continue
		}
		switch currentTable {
		case "":
			if rootDottedFeaturesMemoriesRe.MatchString(trimmed) ||
				rootDottedMemoriesGenerateRe.MatchString(trimmed) ||
				rootDottedMemoriesUseRe.MatchString(trimmed) {
				continue
			}
		case "[features]":
			if featuresTableMemoriesRe.MatchString(trimmed) {
				continue
			}
		case "[memories]":
			if memoriesTableGenerateRe.MatchString(trimmed) ||
				memoriesTableUseRe.MatchString(trimmed) {
				continue
			}
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

// hasRootMemoriesTable reports whether the file contains a top-level
// `[memories]` table header. Sub-tables do NOT count.
func hasRootMemoriesTable(content string) bool {
	for _, line := range strings.Split(content, "\n") {
		if rootMemoriesTableHeaderRe.MatchString(line) {
			return true
		}
	}
	return false
}

func injectMemoryFeatureBlockIntoFeaturesTable(content string) string {
	return injectAfterHeader(content, rootFeaturesTableHeaderRe, renderBoardlyMemoryFeatureBlock(true))
}

func injectMemoryConfigBlockIntoMemoriesTable(content string) string {
	return injectAfterHeader(content, rootMemoriesTableHeaderRe, renderBoardlyMemoryConfigBlock(true))
}

// injectAfterHeader inserts block right after the first line matching
// headerRe. Blank lines that would sit between the inserted block and the
// next non-blank line are dropped so the strip-then-inject rewrite stays
// byte-exact idempotent. The trailing "" element from Split (EOF newline) is
// preserved.
func injectAfterHeader(content string, headerRe *regexp.Regexp, block string) string {
	blockLines := strings.Split(strings.TrimRight(block, "\n"), "\n")
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		if !headerRe.MatchString(line) {
			continue
		}
		tail := lines[i+1:]
		for len(tail) > 1 && tail[0] == "" {
			tail = tail[1:]
		}
		out := make([]string, 0, len(lines[:i+1])+len(blockLines)+len(tail))
		out = append(out, lines[:i+1]...)
		out = append(out, blockLines...)
		out = append(out, tail...)
		return strings.Join(out, "\n")
	}
	return content
}

// ensureCodexMemoryConfig writes the daemon-managed memory blocks into the
// per-run config.toml so Codex native memory stays disabled. Idempotent.
// No-op when BOARDLY_CODEX_MEMORY is truthy.
func ensureCodexMemoryConfig(configPath string, logger *slog.Logger) error {
	if codexMemoryEnabled() {
		if logger != nil {
			logger.Info("codex memory: leaving Codex native memory untouched per BOARDLY_CODEX_MEMORY",
				"config_path", configPath)
		}
		return nil
	}

	data, err := os.ReadFile(configPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read config.toml: %w", err)
	}
	existing := string(data)

	existing = memoryFeatureBlockRe.ReplaceAllString(existing, "")
	existing = memoryConfigBlockRe.ReplaceAllString(existing, "")
	existing = stripUserMemoryDirectives(existing)

	hasFeatures := hasRootFeaturesTable(existing)
	hasMemories := hasRootMemoriesTable(existing)

	// In-table injections happen first so the root-prepended blocks land at
	// the very top of the file (above any user tables).
	if hasFeatures {
		existing = injectMemoryFeatureBlockIntoFeaturesTable(existing)
	}
	if hasMemories {
		existing = injectMemoryConfigBlockIntoMemoriesTable(existing)
	}

	var prepend strings.Builder
	if !hasFeatures {
		prepend.WriteString(renderBoardlyMemoryFeatureBlock(false))
	}
	if !hasMemories {
		prepend.WriteString(renderBoardlyMemoryConfigBlock(false))
	}
	prependStr := prepend.String()

	existing = strings.TrimLeft(existing, "\n")
	if prependStr != "" {
		if existing == "" {
			existing = prependStr
		} else {
			existing = prependStr + "\n" + existing
		}
	}

	if existing == string(data) {
		return nil
	}

	if err := os.WriteFile(configPath, []byte(existing), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}
