package execenv

import (
	"fmt"
	"log/slog"
	"os"
	"regexp"
	"strings"
)

// Recent Codex app-server releases enable `features.multi_agent` by default,
// letting a thread fan out into nested subagents. The daemon models only the
// parent thread per run: when the parent emits `turn/completed` the run goes
// terminal even if spawned children are still working, dropping their output.
// So the daemon disables native multi-agent by default for daemon-managed run
// sessions; only the per-run CODEX_HOME/config.toml is touched.
//
// TOML rejects redefining a table that already exists — including implicitly
// via a dotted key — so the managed block adapts to the user's config: with a
// top-level `[features]` table the override is injected inside it, otherwise
// the block lives at the top of the file in dotted-key form.

// BoardlyCodexMultiAgentEnv keeps Codex native multi-agent enabled inside
// daemon-managed runs when set truthy (1, true, yes, on; case-insensitive).
const BoardlyCodexMultiAgentEnv = "BOARDLY_CODEX_MULTI_AGENT"

const (
	boardlyMultiAgentBeginMarker = "# BEGIN boardly-managed multi-agent (do not edit; regenerated by daemon)"
	boardlyMultiAgentEndMarker   = "# END boardly-managed multi-agent"
)

// `\n*` rather than `\n?` so reruns don't accumulate blank lines when this
// block coexists with the sandbox managed block in the same file.
var multiAgentBlockRe = regexp.MustCompile(
	`(?ms)^` + regexp.QuoteMeta(boardlyMultiAgentBeginMarker) +
		`.*?^` + regexp.QuoteMeta(boardlyMultiAgentEndMarker) + `\n*`)

var (
	rootFeaturesTableHeaderRe = regexp.MustCompile(`^\s*\[\s*features\s*\]\s*(?:#.*)?$`)
	featuresTableMultiAgentRe = regexp.MustCompile(`^\s*multi_agent\s*=`)
	rootDottedMultiAgentRe    = regexp.MustCompile(`^\s*features\s*\.\s*multi_agent\s*=`)
)

func codexMultiAgentEnabled() bool {
	return envTruthy(os.Getenv(BoardlyCodexMultiAgentEnv))
}

func envTruthy(raw string) bool {
	switch strings.ToLower(strings.TrimSpace(raw)) {
	case "1", "true", "yes", "on":
		return true
	}
	return false
}

// renderBoardlyMultiAgentBlock returns the daemon-managed multi-agent block:
// `multi_agent = false` inside a `[features]` table, dotted-key otherwise.
func renderBoardlyMultiAgentBlock(inFeaturesTable bool) string {
	var b strings.Builder
	b.WriteString(boardlyMultiAgentBeginMarker)
	b.WriteString("\n")
	if inFeaturesTable {
		b.WriteString("multi_agent = false\n")
	} else {
		b.WriteString("features.multi_agent = false\n")
	}
	b.WriteString(boardlyMultiAgentEndMarker)
	b.WriteString("\n")
	return b.String()
}

// stripUserMultiAgentDirectives removes `features.multi_agent = ...` at the
// TOML root and `multi_agent = ...` inside a top-level `[features]` table.
// Other tables are preserved untouched.
func stripUserMultiAgentDirectives(content string) string {
	lines := strings.Split(content, "\n")
	out := make([]string, 0, len(lines))
	currentTable := ""
	for _, line := range lines {
		trimmed := strings.TrimSpace(line)
		if rootFeaturesTableHeaderRe.MatchString(line) {
			currentTable = "[features]"
			out = append(out, line)
			continue
		}
		if strings.HasPrefix(trimmed, "[") {
			currentTable = trimmed
			out = append(out, line)
			continue
		}
		switch currentTable {
		case "":
			if rootDottedMultiAgentRe.MatchString(trimmed) {
				continue
			}
		case "[features]":
			if featuresTableMultiAgentRe.MatchString(trimmed) {
				continue
			}
		}
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

// hasRootFeaturesTable reports whether the file contains a top-level
// `[features]` table header. Sub-tables like `[features.experimental]` do
// NOT count.
func hasRootFeaturesTable(content string) bool {
	for _, line := range strings.Split(content, "\n") {
		if rootFeaturesTableHeaderRe.MatchString(line) {
			return true
		}
	}
	return false
}

// injectManagedBlockIntoFeaturesTable inserts the in-table managed block
// immediately after the first `[features]` header line.
func injectManagedBlockIntoFeaturesTable(content string) string {
	block := renderBoardlyMultiAgentBlock(true)
	blockLines := strings.Split(strings.TrimRight(block, "\n"), "\n")
	lines := strings.Split(content, "\n")
	for i, line := range lines {
		if !rootFeaturesTableHeaderRe.MatchString(line) {
			continue
		}
		out := make([]string, 0, len(lines)+len(blockLines))
		out = append(out, lines[:i+1]...)
		out = append(out, blockLines...)
		out = append(out, lines[i+1:]...)
		return strings.Join(out, "\n")
	}
	return content
}

// ensureCodexMultiAgentConfig writes the daemon-managed multi-agent block
// into the per-run config.toml so Codex native subagents stay disabled.
// Idempotent. No-op when BOARDLY_CODEX_MULTI_AGENT is truthy.
func ensureCodexMultiAgentConfig(configPath string, logger *slog.Logger) error {
	if codexMultiAgentEnabled() {
		if logger != nil {
			logger.Info(
				"codex multi-agent: leaving Codex native multi-agent untouched per BOARDLY_CODEX_MULTI_AGENT",
				"config_path",
				configPath,
			)
		}
		return nil
	}

	data, err := os.ReadFile(configPath)
	if err != nil && !os.IsNotExist(err) {
		return fmt.Errorf("read config.toml: %w", err)
	}
	existing := string(data)

	existing = multiAgentBlockRe.ReplaceAllString(existing, "")
	existing = stripUserMultiAgentDirectives(existing)

	var updated string
	if hasRootFeaturesTable(existing) {
		updated = injectManagedBlockIntoFeaturesTable(existing)
	} else {
		existing = strings.TrimLeft(existing, "\n")
		block := renderBoardlyMultiAgentBlock(false)
		if existing == "" {
			updated = block
		} else {
			updated = block + "\n" + existing
		}
	}

	if updated == string(data) {
		return nil
	}

	if err := os.WriteFile(configPath, []byte(updated), 0o644); err != nil {
		return fmt.Errorf("write config.toml: %w", err)
	}
	return nil
}
