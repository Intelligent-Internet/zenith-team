func TestBlockMarkdownDecodesTextEscapes(t *testing.T) {
	t.Parallel()
	for _, test := range []struct{ name, markdown, want string }{
		{"entities", "A &amp; B &#42; &#x1F600;", "A & B * 😀"},
		{"punctuation", `\*literal\* and \\`, `*literal* and \`},
		{"escaped entity", `\&amp;`, `&amp;`},
		{"inline code", "`&amp; \\*literal\\*`", `&amp; \*literal\*`},
		{"code block", "```\n&amp; \\*literal\\*\n```", `&amp; \*literal\*`},
	} {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			root := BlocksFromMarkdown(test.markdown)
			var got strings.Builder
			var walk func(BlockNode)
			walk = func(node BlockNode) {
				got.WriteString(node.Text)
				for _, child := range node.Content {
					walk(child)
				}
			}
			walk(root)
			if got.String() != test.want {
				t.Fatalf("text = %q, want %q", got.String(), test.want)
			}
		})
	}
}

