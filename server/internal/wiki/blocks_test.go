func TestBlockMarkdownMigration(t *testing.T) {
	t.Parallel()
	input := "# Architecture\n\nHello **team** and [docs](https://example.com).\n\n- one\n- two\n\n```mermaid\nflowchart LR\n A --> B\n```\n\n| Name | Value |\n| --- | --- |\n| Budget | 100 |\n"
	root := BlocksFromMarkdown(input)
	AssignBlockIDs(&root, uuid.NewString)
	state, err := EncodeBlocks(root)
	if err != nil {
		t.Fatal(err)
	}
	_, got, markdown, err := MergeBlocks(state, nil)
	if err != nil {
		t.Fatal(err)
	}
	raw, _ := json.Marshal(got)
	for _, want := range []string{`"heading"`, `"bold"`, `"link"`, `"mermaid"`, `"table"`, "Budget"} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("migration content missing %s: %s", want, raw)
		}
	}
	if !strings.Contains(markdown, "flowchart LR") || !strings.Contains(markdown, "Architecture") {
		t.Fatalf("export = %q", markdown)
	}
}

func TestBlockMarkdownPreservesWikiReferences(t *testing.T) {
	t.Parallel()
	page := "11111111-1111-4111-8111-111111111111"
	label := BlocksFromMarkdown("[[" + page + "|A &amp;amp; B]]")
	if got := label.Content[0].Content[0].Attrs["label"]; got != "A &amp; B" {
		t.Fatalf("Wiki label = %q, want A &amp; B", got)
	}
	output := "22222222-2222-4222-8222-222222222222"
	input := "See [[" + page + "|Project plan]] and [[artifact:" + output + "#2]].\n\n[Wiki](/wiki/" + page + ")\n\n`[[artifact:" + output + "]]`"
	root := BlocksFromMarkdown(input)
	AssignBlockIDs(&root, uuid.NewString)
	state, err := EncodeBlocks(root)
	if err != nil {
		t.Fatal(err)
	}
	_, got, markdown, err := MergeBlocks(state, nil)
	if err != nil {
		t.Fatal(err)
	}
	raw, _ := json.Marshal(got)
	for _, want := range []string{`"type":"wikiPageLink"`, `"type":"wikiArtifactRef"`, `"ordinal":2`, `"href":"/wiki/` + page} {
		if !strings.Contains(string(raw), want) {
			t.Errorf("migration missing %s in %s", want, raw)
		}
	}
	if strings.TrimSpace(markdown) != input {
		t.Fatalf("Wiki reference export = %q, want %q", markdown, input)
	}
	table := "| Reference |\n| --- |\n| [[" + page + "|Plan &#124; notes]] |\n"
	root = BlocksFromMarkdown(table)
	AssignBlockIDs(&root, uuid.NewString)
	state, err = EncodeBlocks(root)
	if err != nil {
		t.Fatal(err)
	}
	_, _, markdown, err = MergeBlocks(state, nil)
	if err != nil || !strings.Contains(markdown, "[["+page+"|Plan &#124; notes]]") {
		t.Fatalf("Wiki link in table = %q, %v", markdown, err)
	}
}

