// routeActorTypes is RunProofPolicy's table: every mounted route, keyed by
// method and full path, says whether it accepts a Run (IA-FR1). A Run is the
// member's own session plus a live X-Boardly-Run-Token proof. On a person
// route the proof is refused with 403 human_actor_required before
// authentication and before the handler. TestEveryRouteDeclaresItsActorType
// fails on a mounted route with no entry and on an entry with no route, so a
// new route cannot ship without saying who may call it.
var routeActorTypes = routeActorTypeTable()

// routeActorTypeTable builds the table from the three lists below. The
// person list is applied last, so a route listed twice by mistake refuses a
// Run; the test fails on it as well.
func routeActorTypeTable() map[string]middleware.RouteActorType {
	table := make(
		map[string]middleware.RouteActorType,
		len(runActorRoutes)+len(anyActorRoutes)+len(personActorRoutes),
	)
	for _, route := range runActorRoutes {
		table[route] = middleware.RouteActorTypeRun
	}
	for _, route := range anyActorRoutes {
		table[route] = middleware.RouteActorTypeAny
	}
	for _, route := range personActorRoutes {
		table[route] = middleware.RouteActorTypePerson
	}
	return table
}

