CREATE TABLE huddle_work_proposals (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    company_id uuid NOT NULL,
    huddle_id uuid NOT NULL,
    attempt_id uuid,
    invitation_revision bigint NOT NULL,
    created_by_agent_id uuid NOT NULL,
    agent_name text NOT NULL,
    project_id uuid,
    project_title text NOT NULL,
    task_id uuid,
    task_key text NOT NULL DEFAULT '',
    request_key text NOT NULL,
    request_hash bytea NOT NULL,
    title text NOT NULL,
    brief text NOT NULL,
    state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','rejected')),
    revision bigint NOT NULL DEFAULT 1,
    updated_by_user_id uuid,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(company_id,id),
    UNIQUE(company_id,huddle_id,invitation_revision,request_key),
    FOREIGN KEY(company_id,huddle_id) REFERENCES huddles(company_id,id) ON DELETE CASCADE,
    FOREIGN KEY(company_id,attempt_id) REFERENCES huddle_ai_sessions(company_id,id) ON DELETE SET NULL (attempt_id),
    FOREIGN KEY(company_id,project_id) REFERENCES projects(company_id,id) ON DELETE SET NULL (project_id),
    FOREIGN KEY(company_id,task_id) REFERENCES tasks(company_id,id) ON DELETE SET NULL (task_id)
);
