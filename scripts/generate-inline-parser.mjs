// Share the grammar between browser rendering and server Page validation.
// Only this trusted bundle executes on the server; authored scripts remain AST data.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const require = createRequire(
  new URL("../frontend/package.json", import.meta.url),
);
const { build } = require("esbuild");
const acornLicense = readFileSync(
  join(dirname(require.resolve("acorn/package.json")), "LICENSE"),
  "utf8",
);
const root = fileURLToPath(new URL("../", import.meta.url));
const output = root + "server/internal/wiki/inline_parser.generated.js";
const result = await build({
  entryPoints: [root + "frontend/src/shared/inline-ui/parser.ts"],
  bundle: true,
  write: false,
  format: "iife",
  globalName: "ZenithInline",
  target: "es2020",
  minify: true,
  legalComments: "inline",
  tsconfigRaw: {},
  banner: {
    js:
      "// Code generated by scripts/generate-inline-parser.mjs; DO NOT EDIT.\n/* Acorn\n" +
      acornLicense +
      "*/",
  },
});
const source = result.outputFiles[0].text;
const schema = readFileSync(root + "frontend/src/shared/inline-ui/schema.json", "utf8");
if (process.argv.includes("--check")) {
  if (readFileSync(output, "utf8") !== source)
    throw new Error("Run node scripts/generate-inline-parser.mjs");
} else {
  writeFileSync(output, source);
}

// Keep the authoring guide honest against the executable schema: the guide
// never promises a prop the renderer rejects, and every accepted prop is either
// documented or deliberately classified below.
const skillRoot = root + "server/internal/mcp/tools/builtin/zenith-intelligent-ui/";
const catalog = JSON.parse(schema);
const skill = readFileSync(skillRoot + "SKILL.md", "utf8");
const shared =
  "align,background,border,clip,direction,disableAutoSpacing,flex,flush,gap,height,justify,key,maxHeight,maxWidth,minHeight,minWidth,padding,radius,role,scrollable,theme,width,wrap".split(",");
const documented = new Map();
for (const [, name, props] of skill.matchAll(/^\| `([A-Za-z-]+)` \| ([^|]*) \|/gm)) {
  if (documented.has(name) || !Object.hasOwn(catalog.props, name)) continue;
  const names = props
    .replace(/`/g, "")
    .replace(/\s*\(Zenith: ([^)]*)\)/, ",$1")
    .replace(/^shared \+ |^shared$/, () => shared.join(",") + ",");
  documented.set(name, new Set(names.split(",").map((p) => p.trim()).filter((p) => p && p !== "none")));
}
documented.set("AsyncImage", new Set(skill.match(/^Props: `([^`]+)`/m)[1].split(",")));
documented.set("Chart", new Set(["content"]));
// Zenith's only extensions beyond the final guide, documented in SKILL.md prose.
const extensions = Object.fromEntries(
  ["input", "textarea", "select", "date-picker", "slider", "checkbox", "segmented-control", "radio-group"].map((name) => [name, ["id"]]),
);
// Final-guide contracts kept in docs/intelligent-ui/provider-integrations.md until a
// provider is connected; the schema keeps their grammar.
const provider = {
  AsyncImage: ["query", "ref", "mode", "group"],
  AsyncImageGroup: catalog.props.AsyncImageGroup,
  AsyncVideo: catalog.props.AsyncVideo,
  MapWidgetV2: catalog.props.MapWidgetV2,
  MemoryCite: catalog.props.MemoryCite,
};
const drift = [];
for (const [name, props] of documented)
  for (const prop of props)
    if (!catalog.props[name].includes(prop))
      drift.push(`SKILL.md documents ${name}.${prop}, which the schema rejects`);
for (const [name, props] of Object.entries(catalog.props)) {
  if (name === "escape") continue;
  if (!documented.has(name) && !provider[name]) {
    drift.push(`schema component ${name} is neither documented nor a provider integration`);
    continue;
  }
  for (const prop of props)
    if (
      !documented.get(name)?.has(prop) &&
      !extensions[name]?.includes(prop) &&
      !provider[name]?.includes(prop)
    )
      drift.push(`schema accepts ${name}.${prop}, which SKILL.md does not document`);
}

if (drift.length) throw new Error("Intelligent UI guide drift:\n" + drift.join("\n"));
